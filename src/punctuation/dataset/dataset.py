def _load_lenta2(split: str, limit: int | None) -> List[str]:
    from datasets import load_dataset
    
    ds = load_dataset("Dmitriy007/Lenta2", split="train")
    
    texts: List[str] = []
    for row in ds:
        t = row.get("text")
        # Проверяем, что t не None и является строкой
        if t and isinstance(t, str):
            t = t.strip()
            if t:
                texts.append(t)
        if limit and len(texts) >= limit:
            break
    return texts


def load_texts(
    source: str = "synthetic",
    split: str = "train",
    limit: int | None = None,
    repeat: int = 1,
) -> List[str]:
    """
    Возвращает список "сырых" текстов.

    repeat — сколько раз продублировать синтетический корпус (для демо-обучения
             на нескольких эпохах полезно иметь чуть больше примеров).
    """
    if source == "synthetic":
        texts = list(_SYNTHETIC) * max(1, repeat)
        if limit:
            texts = texts[:limit]
        return texts
    elif source == "lenta2":
        return _load_lenta2(split=split, limit=limit)
    else:
        raise ValueError(f"Неизвестный source: {source!r}")

   
    


